/* ===================== 软件 I2C（PB6=SCL, PB7=SDA） ===================== */
static void I2C_Delay(void)  { Delay_us(3); }          // 约 150kHz，稳即可

static void SCL_Set(uint8_t v) { if (v) GPIO_SetBits(SSD1306_I2C_PORT, SSD1306_SCL_PIN);
                                 else   GPIO_ResetBits(SSD1306_I2C_PORT, SSD1306_SCL_PIN); }
static void SDA_Set(uint8_t v) { if (v) GPIO_SetBits(SSD1306_I2C_PORT, SSD1306_SDA_PIN);
                                 else   GPIO_ResetBits(SSD1306_I2C_PORT, SSD1306_SDA_PIN); }
static uint8_t SDA_Get(void)  { return GPIO_ReadInputDataBit(SSD1306_I2C_PORT, SSD1306_SDA_PIN); }

static void I2C_Start(void)
{
    SDA_Set(1); SCL_Set(1); I2C_Delay();
    SDA_Set(0); I2C_Delay();
    SCL_Set(0); I2C_Delay();
}

static void I2C_Stop(void)
{
    SCL_Set(0); SDA_Set(0); I2C_Delay();
    SCL_Set(1); I2C_Delay();
    SDA_Set(1); I2C_Delay();
}

/* 写一字节，返回 ACK（1=收到应答，0=无应答） */
static uint8_t I2C_WriteByte(uint8_t data)
{
    for (uint8_t i = 0; i < 8; i++)
    {
        SCL_Set(0); I2C_Delay();
        SDA_Set((data & 0x80) ? 1 : 0);
        data <<= 1;
        SCL_Set(1); I2C_Delay();
        SCL_Set(0);
    }
    /* 第 9 个时钟读 ACK：释放 SDA，SCL 拉高后读电平（低=ACK） */
    SDA_Set(1); I2C_Delay();
    SCL_Set(1); I2C_Delay();
    uint8_t ack = SDA_Get() ? 0 : 1;
    SCL_Set(0);
    return ack;
}

/* 写命令 / 写数据（SSD1306 控制字节 0x00=命令, 0x40=数据） */
static void SSD1306_WriteCmd(uint8_t cmd)
{
    I2C_Start();
    I2C_WriteByte(SSD1306_I2C_ADDR);
    I2C_WriteByte(0x00);
    I2C_WriteByte(cmd);
    I2C_Stop();
}

static void SSD1306_WriteData(uint8_t data)
{
    I2C_Start();
    I2C_WriteByte(SSD1306_I2C_ADDR);
    I2C_WriteByte(0x40);
    I2C_WriteByte(data);
    I2C_Stop();
}

